"""Generate the Lakewatch rules in lakewatch/rules/cwda_*.yaml from this repository's detections.

One source of truth: the SQL of each rule is the Genie Agent function that ports the notebook
(genie-agent/functions/*.sql, inlined with genie-agent/tools/inline_functions.py and called with the
same arguments the agent template passes), and the metadata (description, objective, severity,
fidelity, MITRE) comes from the dscc YAML header of the notebook (base/detections/**/<name>.py).
Fix a detection there, run this script, and the rule follows. tests/test_rules.py fails when a
generated file is out of date.

Transform of the function body into a v2 rule query:
  - `<col> BETWEEN :start_time AND :end_time`  ->  `IN_TIMERANGE(<col>)` (the run window)
  - any other use of start_time / end_time (for example a baseline that ends before the window)
    -> `(TIMERANGE_NOW() - INTERVAL <window>)` / `TIMERANGE_NOW()`
  - `system.access.audit` -> `{{audit_table}}` (deploy.py fills it; default system.access.audit)
  - each top-level SELECT item gets `AS <column>`: the rule runtime drops a derived-table column list
  - optional `where` per rule: a threshold over the function output (for functions that return a
    volume table rather than detections)

Usage (from the repository root):
    uv run lakewatch/tools/build_rules.py            # write lakewatch/rules/cwda_*.yaml
    uv run lakewatch/tools/build_rules.py --check    # exit 1 if a file is out of date
"""
