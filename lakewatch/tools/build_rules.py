class _Literal(str):
    pass


def _literal(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")


yaml.add_representer(_Literal, _literal, Dumper=yaml.SafeDumper)


def read_dscc(nb_path: Path) -> dict:
    """The dscc block of the ```yaml cell of a detection notebook."""
    lines, grab = [], False
    for ln in nb_path.read_text().splitlines():
        s = ln[len("# MAGIC "):] if ln.startswith("# MAGIC ") else ("" if ln.strip() == "# MAGIC" else None)
        if s is None:
            if grab:
                break
            continue
        if s.strip() == "```yaml":
            grab = True
            continue
        if grab and s.strip() == "```":
            break
        if grab:
            lines.append(s)
    return (yaml.safe_load("\n".join(lines)) or {}).get("dscc", {}) if lines else {}


def mitre_from(taxonomy: list) -> list:
    tactic = next((TACTICS.get(t.split(".")[1]) for t in taxonomy if re.match(r"MITRE\.TA\d{4}", str(t))), None)
    out = []
    for t in taxonomy:
        m = re.match(r"MITRE\.(T\d{4})(?:\.\d{3})?\.([A-Za-z_]+)$", str(t))
        if m:
            out.append({"taxonomy": "Enterprise", "tactic": tactic or TECH_TACTIC.get(m.group(1), ""),
                        "technique_id": m.group(1), "technique": m.group(2).replace("_", " ")})
    return [x for x in out if x["tactic"]]


def _top_level(s: str):
    """(index, char, depth) for chars outside string literals and comments."""
    depth, i, n = 0, 0, len(s)
    while i < n:
        c = s[i]
        if c in "'\"`":
            j = i + 1
            while j < n and s[j] != c:
                j += 2 if s[j] == "\\" else 1
            i = j + 1
            continue
        if s.startswith("--", i):
            j = s.find("\n", i)
            i = n if j < 0 else j
            continue
        depth += {"(": 1, ")": -1}.get(c, 0)
        yield i, c, depth
        i += 1


def alias_outer_select(body: str, columns: list[str]) -> str:
    """Give each top-level SELECT item an explicit `AS <column>` (the RETURNS TABLE name)."""
    sel = frm = None
    for i, c, d in _top_level(body):
        if d != 0 or not c.isalpha():
            continue
        if sel is None and re.match(r"SELECT\b", body[i:], re.I) and (i == 0 or not body[i - 1].isalnum()):
            sel = i + len("SELECT")
        elif sel is not None and re.match(r"FROM\b", body[i:], re.I) and not body[i - 1].isalnum():
            frm = i
            break
    if sel is None or frm is None:
        raise ValueError("no top-level SELECT ... FROM")
    head = body[sel:frm]
    m = re.match(r"\s*(DISTINCT\s+)?", head, re.I)
    prefix, src = head[:m.end()], head[m.end():]
    items, start = [], 0
    for i, c, d in _top_level(src):
        if c == "," and d == 0:
            items.append(src[start:i])
            start = i + 1
    items.append(src[start:])
    items = [x.strip() for x in items if x.strip()]
    if items == ["*"]:  # SELECT * over an inner query that names its columns already
        return body
    if len(items) != len(columns):
        raise ValueError(f"{len(items)} select items vs {len(columns)} RETURNS TABLE columns")
    named = [f"{re.sub(r'\s+AS\s+`?\w+`?\s*$', '', it, flags=re.I)} AS {col}" for it, col in zip(items, columns)]
    return body[:sel] + " " + prefix + ",\n    ".join(named) + "\n  " + body[frm:]


# Allow-list step: every rule drops findings that match a row in {{allowlist_table}}.
def _main_select_pos(sql: str) -> int:
    depth, i, n = 0, 0, len(sql)
    while i < n:
        c = sql[i]
        if c == "'":
            i += 1
            while i < n and sql[i] != "'":
                i += 2 if sql[i] == "\\" else 1
        elif sql.startswith("--", i):
            i = sql.find("\n", i)
            if i < 0:
                break
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif depth == 0 and re.match(r"(?i)select\b", sql[i:i + 7]) and (i == 0 or not (sql[i - 1].isalnum() or sql[i - 1] == "_")):
            return i
        i += 1
    raise ValueError("no top-level SELECT")

def with_allowlist(sql: str, rule: str, has_actor: bool, has_ip: bool) -> str:
    sql = sql.rstrip().rstrip(";")
    pos = _main_select_pos(sql)
    head, main = sql[:pos].rstrip(), sql[pos:]
    conds = ["al.rule IN ('*', '%s')" % rule,
             "(al.expires_at IS NULL OR al.expires_at > TIMERANGE_NOW())",
             "(al.principal IS NOT NULL OR al.src_ip IS NOT NULL)",
             "(al.principal IS NULL OR al.principal = f.actor)" if has_actor else "al.principal IS NULL",
             "(al.src_ip IS NULL OR al.src_ip = f.src_ip)" if has_ip else "al.src_ip IS NULL"]
    body = "\n".join("  " + l if l else l for l in main.splitlines())
    tail = ("findings AS (\n" + body + "\n)\n"
            "-- Allow-list: drop findings that match a row in the allow-list table (tune there, not here)\n"
            "SELECT f.* FROM findings AS f\n"
            "WHERE NOT EXISTS (\n  SELECT 1 FROM {{allowlist_table}} AS al\n  WHERE " + "\n    AND ".join(conds) + ")")
    return (head + ",\n" + tail) if head else ("WITH " + tail)


# The Genie functions skip their own detection text by a marker in the command or query text. Anyone can put the
# marker in a comment, so in the Lakewatch rules it counts only for the identity the rules run as.
RUNNER_MARKERS = [
    ("AND lower(q.statement_text) NOT LIKE '%encoding_technique%'",
     "AND NOT (q.executed_by = '{{runner_principal}}' AND lower(q.statement_text) LIKE '%encoding_technique%')"),
    ("WHERE lower(COALESCE(a.cmd, '')) NOT LIKE '%encoding_technique%'",
     "WHERE NOT (COALESCE(a.user_identity.email, '') = '{{runner_principal}}'\n"
     "                   AND lower(COALESCE(a.cmd, '')) LIKE '%encoding_technique%')"),
]

# Lakewatch runs each rule by exporting the notebook it generated under the run-as identity's home
# (notebooks/rules/lakewatch-rule-*), from rotating private IPs. A new runner has no network history, so every
# hourly run looks like "own home, new network". Drop only those exports: actor is the runner AND the path is the
# rules folder. A row in the allow-list table can't do this (it matches principal/IP, not path) and would hide
# every export by the runner, including theft with its credentials.
RUNNER_OWN = {
    "bulk_notebook_export": [
        (r"(WHERE a\.action_name = 'workspaceExport'\n(\s*)AND IN_TIMERANGE\(a\.event_time\))",
         r"\1\n\2AND NOT (COALESCE(a.user_identity.email, '') = '{{runner_principal}}'"
         r"\n\2     AND startswith(COALESCE(a.request_params['notebookFullPath'], ''),"
         r"\n\2                    '/Workspace/Users/{{runner_principal}}/notebooks/rules/lakewatch-rule-'))"),
    ],
}


def rule_sql(func, args: list[str], spec: dict, window: str) -> str:
    body = func.body
    for pname, value in zip(func.params, args):  # same rule as inline_functions._substitute_params
        body = re.sub(r"(?<![\w.])" + re.escape(pname) + r"\b", lambda _m, v=value: v, body)
    body = alias_outer_select(body, func.columns)
    sql, n = re.subn(r"([\w.]+)\s+BETWEEN\s+:start_time\s+AND\s+:end_time", r"IN_TIMERANGE(\1)", body)
    if n == 0:
        raise ValueError("no `<col> BETWEEN :start_time AND :end_time` to turn into IN_TIMERANGE")
    sql = sql.replace(":start_time", f"(TIMERANGE_NOW() - INTERVAL {window})").replace(":end_time", "TIMERANGE_NOW()")
    sql = re.sub(r"\bsystem\.access\.audit\b", "{{audit_table}}", sql)
    sql = "\n".join(line.rstrip() for line in sql.strip().splitlines())
    time_col = next((c for c in ("event_time", "start_time_ts", "last_seen") if c in func.columns), None)
    extra = None
    if time_col is None and "event_date" in func.columns:
        time_col, extra = "event_ts", "CAST(event_date AS TIMESTAMP) AS event_ts"
    if extra or spec.get("where"):
        sql = (f"SELECT *{', ' + extra if extra else ''}\nFROM (\n{sql}\n) AS r"
               + (f"\nWHERE {spec['where']}" if spec.get("where") else ""))
    return sql, time_col


def build(root: Path = ROOT) -> dict[str, str]:
    """{file name: YAML text} for every spec."""
    sys.path.insert(0, str(root / "genie-agent" / "tools"))
    import inline_functions as IF  # noqa: E402

    funcs = IF.parse_functions(root / "genie-agent" / "functions")
    tmpl = json.dumps(json.loads((root / "genie-agent/agent/serialized_space.template.json").read_text()))
    flat = tmpl.replace("\\n", "").replace('", "', "")
    calls = {}
    for m in re.finditer(r"(detect_\w+)\(([^)]*)\)", flat):
        calls.setdefault(m.group(1), [x.strip() for x in m.group(2).split(",") if x.strip()])
    out = {}
    for key, spec in SPECS.items():
        func = funcs[spec["fn"]]
        args = calls.get(spec["fn"]) or [":start_time", ":end_time"]
        if len(args) != len(func.params):
            raise ValueError(f"{spec['fn']}: template passes {len(args)} args, function takes {len(func.params)}")
        every, lookback = SCHEDULE[spec["kind"]]
        window = {"1h": "1 HOUR", "24h": "24 HOURS"}[every]
        sql, time_col = rule_sql(func, args, spec, window)
        for old, new in RUNNER_MARKERS:  # a text marker excludes only the rule runner's own SQL
            sql = sql.replace(old, new)
        for pattern, repl in RUNNER_OWN.get(key, []):
            sql, n = re.subn(pattern, repl, sql)
            if n != 1:
                raise ValueError(f"{key}: runner exclusion anchor matched {n} times: {pattern!r}")
        cols_out = set(func.columns) | ({"event_ts"} if time_col == "event_ts" else set())
        actor_col = next((c for c in ACTOR_COLS if c in cols_out), None)
        ip_col = next((c for c in IP_COLS if c in cols_out), None)
        sql = with_allowlist(sql, PREFIX + key, actor_col is not None, ip_col is not None)
        if actor_col and actor_col != "actor":
            sql = sql.replace("al.principal = f.actor", f"al.principal = f.{actor_col}")
        if ip_col and ip_col != "src_ip":
            sql = sql.replace("al.src_ip = f.src_ip", f"al.src_ip = f.{ip_col}")
        det = read_dscc(root / "base" / "detections" / f"{spec['nb']}.py").get("detection", {})
        cols = [c for c in func.columns if c not in SKIP_CONTEXT]
        context = {c: f"{{{c}}}" for c in cols}
        actor = next((c for c in ACTOR_COLS if c in cols), None)
        ip = next((c for c in IP_COLS if c in cols), None)
        if actor and actor != "actor":
            context["actor"] = f"{{{actor}}}"
        if ip and ip != "src_ip":
            context["src_ip"] = f"{{{ip}}}"
        rule = {
            "catalog_name": "{{catalog}}",
            "schema_name": "{{schema}}",
            "rule_name": PREFIX + key,
            "description": str(det.get("description") or det.get("name") or key).strip(),
            "severity": SEVERITY.get(str(det.get("severity", "medium")).lower(), "Medium"),
            "category": "Behavioral" if spec["kind"] == "agg" else "Static Signature",
            "fidelity": FIDELITY.get(str(det.get("fidelity", "low")).lower(), "FIDELITY_INVESTIGATIVE"),
            "objective": str(det.get("objective") or "").strip(),
        }
        mitre = mitre_from(det.get("taxonomy") or [])
        if mitre:
            rule["mitre"] = mitre
        rule.update({
            "deduplication": "DEDUPLICATION_ENABLED",
            "deduplication_time_window": "24 hours",
            "schedule": {"at_least_every": every, "enabled": False},
            "timerange": {"extend_lookback": lookback},
            "batch": {"warehouse_id": "{{warehouse_id}}", "sql": {"query": _Literal(sql + "\n")}},
            "output": {"summary": spec["summary"], "event_time_column": time_col,
                       "context": context, "default_context": False},
            "annotations": {"source": "cybersec-workspace-detection-app",
                            "source_notebook": f"base/detections/{spec['nb']}.py",
                            "source_function": spec["fn"]},
        })
        text = HEADER.format(fn=spec["fn"], source=f"base/detections/{spec['nb']}.py") + yaml.safe_dump(
            rule, sort_keys=False, width=110, allow_unicode=True)
        out[f"{PREFIX}{key}.yaml"] = text
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when a generated file is missing or stale")
    a = ap.parse_args()
    files = build()
    stale = [n for n, t in files.items() if not (RULES / n).is_file() or (RULES / n).read_text() != t]
    if a.check:
        for n in stale:
            print(f"stale: lakewatch/rules/{n}")
        return 1 if stale else 0
    RULES.mkdir(parents=True, exist_ok=True)
    for n, t in files.items():
        (RULES / n).write_text(t)
    print(f"wrote {len(files)} rules to lakewatch/rules/ ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
